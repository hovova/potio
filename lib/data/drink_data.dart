class _DrinkSpec {
  final String id;
  final String name;
  final Map<String, String> category;
  final Map<String, String> baseSpirit;
  final String imageEmoji;
  final Map<String, String> shortDescription;
  final Map<String, String> origin;
  final Map<String, String> glassType;
  final Map<String, String> ice;
  final Map<String, String> method;
  final Map<String, String> garnish;
  final Map<String, String> tasteProfile;
  final Map<String, String> difficulty;
  final bool isAlcoholic;
  final bool isPremium;
  final Map<String, List<String>> ingredients;
  final Map<String, List<String>> recipeSteps;
  final Map<String, List<String>> allergens;
  final Map<String, List<String>> tags;

  const _DrinkSpec({
    required this.id,
    required this.name,
    required this.category,
    required this.baseSpirit,
    required this.imageEmoji,
    required this.shortDescription,
    required this.origin,
    required this.glassType,
    required this.ice,
    required this.method,
    required this.garnish,
    required this.tasteProfile,
    required this.difficulty,
    this.isAlcoholic = true,
    this.isPremium = false,
    required this.ingredients,
    required this.recipeSteps,
    required this.allergens,
    required this.tags,
  });

  Drink toDrink(String language) {
    return Drink(
      id: id,
      name: name,
      category: _text(category, language),
      baseSpirit: _text(baseSpirit, language),
      imageEmoji: imageEmoji,
      shortDescription: _text(shortDescription, language),
      origin: _text(origin, language),
      glassType: _text(glassType, language),
      ice: _text(ice, language),
      method: _text(method, language),
      garnish: _text(garnish, language),
      tasteProfile: _text(tasteProfile, language),
      difficulty: _text(difficulty, language),
      isAlcoholic: isAlcoholic,
      isPremium: isPremium,
      ingredients: _texts(ingredients, language),
      recipeSteps: _texts(recipeSteps, language),
      allergens: _texts(allergens, language),
      tags: _texts(tags, language),
    );
  }
}

String _text(Map<String, String> value, String language) {
  return value[language] ?? value['en'] ?? '';
}

List<String> _texts(Map<String, List<String>> value, String language) {
  return value[language] ?? value['en'] ?? const [];
}