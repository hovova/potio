    required this.ingredients,
    required this.recipeSteps,
    required this.allergens,
    required this.tags,
  });

  Drink toDrink(String language) {
    return Drink(
      id: id,
      name: name,
      category: _text(category, language),
      baseSpirit: _text(baseSpirit, language),
      imageEmoji: imageEmoji,
      shortDescription: _text(shortDescription, language),
      origin: _text(origin, language),
      glassType: _text(glassType, language),
      ice: _text(ice, language),
      method: _text(method, language),
