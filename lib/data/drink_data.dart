import '../models/drink.dart';
import '../services/language_service.dart';

List<Drink> get basicDrinks {
  return localizedBasicDrinks(LanguageService.instance.languageCode.value);
}

List<Drink> get allDrinks {
  final lang = LanguageService.instance.languageCode.value;
  return [
    ...localizedBasicDrinks(lang),
    ...localizedPremiumDrinks(lang),
  ];
}

List<Drink> localizedBasicDrinks(String languageCode) {
  final language = switch (languageCode) {
    'uk' => 'uk',
    'ru' => 'ru',
    _ => 'en',
  };

  return _freeDrinkSpecs.map((spec) => spec.toDrink(language)).toList();
}

List<Drink> localizedPremiumDrinks(String languageCode) {
  final language = switch (languageCode) {
    'uk' => 'uk',
    'ru' => 'ru',
    _ => 'en',
  };

  return _premiumDrinkSpecs.map((spec) => spec.toDrink(language)).toList();
}

